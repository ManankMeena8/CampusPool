    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing: android/key.properties (gitignored, see key.properties.example) points at a
// keystore kept outside the repo. Without it, release builds fall back to the debug key, which
// is fine for `flutter run --release` but not for an APK to hand out.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseKey = keystorePropertiesFile.exists()
if (hasReleaseKey) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

fun keystoreProperty(name: String): String =
    keystoreProperties.getProperty(name)?.takeIf { it.isNotBlank() }
        ?: throw GradleException("key.properties has no $name")

android {
    namespace = "com.campuspool.campuspool"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        // flutter_local_notifications needs java.time on older Android versions.
        isCoreLibraryDesugaringEnabled = true
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = JavaVersion.VERSION_17.toString()
    }

    defaultConfig {
        // Must match the Android app registered in Firebase (google-services.json).
        applicationId = "com.campuspool.campuspool"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        if (hasReleaseKey) {
            create("release") {
                val keystore = file(keystoreProperty("storeFile"))
                if (!keystore.exists()) {
                    throw GradleException("Release keystore not found: $keystore (key.properties storeFile)")
                }
                storeFile = keystore
                storePassword = keystoreProperty("storePassword")
                keyAlias = keystoreProperty("keyAlias")
                keyPassword = keystoreProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = if (hasReleaseKey) {
                signingConfigs.getByName("release")
            } else {
                logger.warn("key.properties not found: the release build is signed with the DEBUG key.")
                signingConfigs.getByName("debug")
            }
        }
    }
}

